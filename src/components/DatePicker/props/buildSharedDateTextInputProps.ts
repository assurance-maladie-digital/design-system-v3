import { type Ref } from 'vue'
import type { DatePickerCommonProps } from '../types'
import type { DatePickerFieldAppearance } from '../composables/useDatePickerFieldAppearance'

export const buildSharedDateTextInputProps = (
	props: DatePickerCommonProps,
	labelWithAsterisk: Ref<string | undefined>,
	errorMessages: Ref<string[]>,
	warningMessages: Ref<string[]>,
	successMessages: Ref<string[]>,
	appearance: DatePickerFieldAppearance,
) => ({
	'date-format-return': props.dateFormatReturn,
	'format': props.format,
	'label': labelWithAsterisk.value,
	'placeholder': props.placeholder,
	'required': props.required,
	'custom-rules': props.customRules,
	'custom-success-rules': props.customSuccessRules,
	'custom-warning-rules': props.customWarningRules,
	'disabled': props.disabled,
	'readonly': props.readonly,
	'clearable': props.clearable,
	'disable-click-button': false,
	'is-outlined': props.isOutlined,
	'display-icon': props.displayIcon,
	'display-append-icon': props.displayAppendIcon,
	'display-prepend-icon': props.displayPrependIcon,
	'no-icon': props.noIcon,
	'disable-error-handling': props.disableErrorHandling,
	'show-success-messages': props.showSuccessMessages,
	'bg-color': props.bgColor,
	'density': appearance.density,
	'hide-details': props.hideDetails,
	'auto-clamp': props.autoClamp,
	'error-messages': errorMessages.value,
	'has-error': props.hasError,
	'has-warning': props.hasWarning,
	'has-success': props.hasSuccess,
	'warning-messages': warningMessages.value,
	'success-messages': successMessages.value,
	'display-asterisk': props.displayAsterisk,
	'is-validate-on-blur': props.isValidateOnBlur,
	'max-errors': props.maxErrors,
	'title': props.title === false ? props.title : props.title || props.placeholder || undefined,
	'hint': props.hint,
	'persistent-hint': props.persistentHint,
	'use-vuetify-validation': props.useVuetifyValidation,
	'rules': props.rules,
	'validate-with-return-format': props.validateWithReturnFormat,
})
